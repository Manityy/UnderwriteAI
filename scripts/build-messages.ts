function sectionKey(section: string): string {
  const map: Record<string, string> = {
    "System & exposure": "systemExposure",
    "Exposure & data": "exposureData",
    Controls: "controls",
    "Testing & compliance": "testingCompliance",
    "History & attestation": "historyAttestation",
  };
  return map[section] ?? section;
}

function buildQuestionnaire(locale: "en" | "fr" | "ar") {
  const raw = loadJson(join("messages", `_questionnaire-${locale}.json`)) as {
    sections: string[];
    questions: Record<
      string,
      { title: string; help: string; section: string; options: Record<string, string> }
    >;
  };

  // Always use English section names as keys for lookup stability
  const enRaw = loadJson(join("messages", "_questionnaire-en.json")) as typeof raw;
  const sections: Record<string, string> = {};
  for (let i = 0; i < enRaw.sections.length; i++) {
    const key = sectionKey(enRaw.sections[i]);
    sections[key] = raw.sections[i] ?? enRaw.sections[i];
  }

  const questions: Record<string, unknown> = {};
  for (const [id, q] of Object.entries(raw.questions)) {
    const enQ = enRaw.questions[id];
    questions[id] = {
      title: q.title,
      help: q.help,
      sectionKey: sectionKey(enQ.section),
      options: q.options,
    };
  }

  return { sections, questions };
}

function main() {
  mkdirSync("messages", { recursive: true });
  const risk = loadJson(join("messages", "_risk-content.json")) as Record<
    string,
    Dict
  >;

  for (const locale of ["en", "fr", "ar"] as const) {
    const messages = {
      ...ui[locale],
      questionnaire: buildQuestionnaire(locale),
      risk: risk[locale] ?? risk.en,
    };
    writeFileSync(
      join("messages", `${locale}.json`),
      JSON.stringify(messages, null, 2),
      "utf8"
    );
    console.log(`wrote messages/${locale}.json`);
  }
}

main();
